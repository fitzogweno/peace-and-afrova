import { NextResponse, after } from 'next/server'
import { requireAdmin } from '../../../lib/auth-admin'
import { supabaseAdmin } from '../../../lib/supabase-admin'
import { sendWhatsAppMessage } from '../../../lib/whatsapp'
import { isEmail } from '../../../lib/html'

export async function POST(req: Request) {
  const auth = await requireAdmin(req)
  if (!auth.ok) return auth.response

  try {
    const {
      quotationId, serviceDescription, confirmationNumber, driverName, driverPhone,
      driverEmail, vehiclePlate, bookingRef, clientEmail, clientName,
    } = await req.json()

    if (!quotationId || !serviceDescription) {
      return NextResponse.json({ error: 'quotationId and serviceDescription are required' }, { status: 400 })
    }

    // Upsert keeps the assignment idempotent; access_token (the driver's magic-link key) is generated by the database.
    const { data: job, error } = await supabaseAdmin()
      .from('supplier_bookings')
      .upsert(
        {
          quotation_id: quotationId,
          service_description: serviceDescription,
          confirmation_number: confirmationNumber,
          driver_name: driverName,
          driver_phone: driverPhone,
          driver_email: driverEmail,
          vehicle_plate: vehiclePlate,
          supplier_name: 'ATS',
          status: 'Booked',
        },
        { onConflict: 'quotation_id,service_description' }
      )
      .select('id, access_token')
      .single()
    if (error) throw error

    const origin = process.env.NEXT_PUBLIC_SITE_URL || new URL(req.url).origin
    const jobLink = `${origin}/driver/job/${job.access_token}`
    const authHeader = req.headers.get('authorization') || ''
    const post = (path: string, payload: unknown) =>
      fetch(`${origin}${path}`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json', Authorization: authHeader },
        body: JSON.stringify(payload),
      }).then((r) => { if (!r.ok) console.error(`${path} responded ${r.status}`) })

    // after() keeps the work alive on Vercel after the response is sent. A bare un-awaited fetch can be killed.
    after(async () => {
      const tasks: Promise<unknown>[] = []
      if (isEmail(clientEmail)) {
        tasks.push(post('/api/send-update', { bookingRef, clientEmail, clientName, updateType: 'booked' }))
      }
      if (isEmail(driverEmail)) {
        tasks.push(post('/api/send-driver-email', { driverEmail, driverName, bookingRef, jobLink }))
      }
      if (driverPhone) {
        tasks.push(sendWhatsAppMessage(
          driverPhone,
          `Hello ${driverName}, you have a new job for Peace and Afrova.\n\nClient: ${clientName}\nService: ${serviceDescription}\nRef: ${bookingRef}\n\nOpen your job card: ${jobLink}`
        ))
      }
      const results = await Promise.allSettled(tasks)
      results.forEach((r) => { if (r.status === 'rejected') console.error('Notification failed:', r.reason) })
    })

    return NextResponse.json({ success: true })
  } catch (error: any) {
    console.error('SUPPLIER BOOKING ERROR:', error)
    return NextResponse.json({ error: 'Could not save the supplier booking' }, { status: 500 })
  }
}
